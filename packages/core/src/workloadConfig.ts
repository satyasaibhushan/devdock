/** Shared guidelines templates devdock knows how to speed up, keyed by the
 *  `subPath` a repo imports from vmockinc/guidelines. */
type Template = 'ui' | 'non-ui'
type Patch = Record<string, unknown>

/** The `devdock` profile layered over each template for devdock's own
 *  deploy/dev/purge verbs. Never applied with `-p persistent` (sandboxes): that
 *  profile removes the same kaniko block and would fail on a second removal. */
const TUNING: Record<Template, Patch[]> = {
  // Dev images were built by kaniko with `cache: false`, so every deploy re-ran
  // apk + a full pnpm install. Build with the same in-cluster BuildKit the
  // `persistent` profile uses (one shared warm builder) and a registry cache.
  ui: [
    { op: 'remove', path: 'images.app.kaniko' },
    {
      op: 'add',
      path: 'images.app.buildKit',
      value: {
        inCluster: { nodeSelector: 'node.kubernetes.io/instance-type=t3a.xlarge' },
        // Inline cache rides in the pushed image itself, so there is no separate
        // ~5s cache export; single-stage Dockerfiles lose nothing to min mode.
        // The `-cache` ref only seeds the first build after switching.
        args: [
          '--cache-to=type=inline',
          '--cache-from=type=registry,ref=${AWS_ECR_DEVSPACE_REPO}:${IMAGE_TAG}',
          '--cache-from=type=registry,ref=${AWS_ECR_DEVSPACE_REPO}:${IMAGE_TAG}-cache',
        ],
      },
    },
  ],
  'non-ui': [],
}

/** The templates' ECR login ran on every deploy (~1.5s: list profiles, mint a
 *  token, docker login). A docker login lasts 12h; reuse it for six. Same
 *  commands as the guidelines' function, which this replaces in the overlay. */
const ECR_LOGIN = `stamp="$HOME/.devdock/ecr-login.stamp"
if [ -n "$(find "$stamp" -mmin -360 2>/dev/null)" ]; then
  echo "Reusing the ECR login from the last six hours"
else
  has_devspace_profile=$(aws configure list-profiles | grep "\${AWS_DEVSPACE_PROFILE_NAME}" | wc -l )
  profileArg=
  if [ $has_devspace_profile -eq 1 ]; then
    profileArg=" --profile \${AWS_DEVSPACE_PROFILE_NAME}"
  fi
  aws ecr get-login-password --region "\${AWS_REGION}" \${profileArg} | docker login --username AWS --password-stdin "\${AWS_ECR_DEVSPACE_REPO}" && mkdir -p "$HOME/.devdock" && touch "$stamp"
fi`

export const DEVDOCK_PROFILE = 'devdock'
const GENERATED = '# Generated by devdock; overwritten on every verb.\n'
/** DevSpace `git pull`s every git import on every verb (~1.5s each). The
 *  overlay reads its own checkout instead and refreshes it in the background. */
const GUIDELINES_REFRESH_MS = 10 * 60_000

interface GuidelinesImport {
  template: Template
  index: number
  git: string
  branch: string
  subPath: string
}

function guidelinesImport(configText: string): GuidelinesImport | undefined {
  let doc: unknown
  try {
    doc = parseYaml(configText)
  } catch {
    return undefined
  }
  const imports = (doc as { imports?: unknown } | null)?.imports
  if (!Array.isArray(imports)) return undefined
  for (const [index, entry] of imports.entries()) {
    const { git, subPath, branch } = (entry ?? {}) as Record<string, unknown>
    if (typeof git !== 'string' || !/[/:]vmockinc\/guidelines(\.git)?$/.test(git)) continue
    const m = typeof subPath === 'string' ? /devspace\/(ui|non-ui)\/?$/.exec(subPath) : null
    if (!m || typeof subPath !== 'string') continue
    const ref = typeof branch === 'string' && branch ? branch : 'master'
    return { template: m[1] as Template, index, git, branch: ref, subPath }
  }
  return undefined
}

export function guidelinesTemplate(configText: string): Template | undefined {
  return guidelinesImport(configText)?.template
}

/** DevSpace's own checkout of a git import (`<url as dashes>-<branch>`). */
export function guidelinesCacheDir(git: string, branch: string): string {
  const root =
    process.env.DEVDOCK_DEVSPACE_DEPENDENCIES ?? join(homedir(), '.devspace', 'dependencies')
  return join(root, `${git.replace(/[^A-Za-z0-9]+/g, '-')}-${branch}`)
}

interface OverlayPlan {
  text: string
  imp: GuidelinesImport
  patches: Patch[]
  /** The template mints an ECR pull secret on every config load. */
  pullSecrets: boolean
}

function overlayPlan(repo: Repo): OverlayPlan | undefined {
  let text: string
  try {
    text = readFileSync(repo.configPath, 'utf8')
  } catch {
    return undefined
  }
  const imp = guidelinesImport(text)
  if (!imp) return undefined
  const seed = cacheSeed(text)
  const patches = TUNING[imp.template].map((patch) => {
    const value = patch.value as { args?: string[] } | undefined
    if (seed === undefined || patch.path !== 'images.app.buildKit' || !value?.args) return patch
    const from = `--cache-from=type=registry,ref=\${AWS_ECR_DEVSPACE_REPO}:${seed}`
    return { ...patch, value: { ...value, args: [...value.args, from] } }
  })
  const repoDoc = (parseYamlSafe(text) ?? {}) as ConfigShape
  const template = parseYamlSafe(
    readOptional(join(guidelinesCacheDir(imp.git, imp.branch), imp.subPath, 'devspace.yaml')),
  ) as ConfigShape | undefined
  patches.push(...localChartPatches(template, repoDoc))
  if (imp.template === 'ui') patches.push(...noSyncWaitPatches(repoDoc))
  const pullSecrets = template?.pullSecrets !== undefined || repoDoc.pullSecrets !== undefined
  return { text, imp, patches, pullSecrets }
}

type ConfigShape = {
  pullSecrets?: unknown
  deployments?: Record<string, { helm?: { chart?: { git?: unknown } } }>
  dev?: Record<string, { sync?: unknown[] }>
}

function parseYamlSafe(text: string | undefined): unknown {
  if (text === undefined) return undefined
  try {
    return parseYaml(text)
  } catch {
    return undefined
  }
}

function readOptional(path: string): string | undefined {
  try {
    return readFileSync(path, 'utf8')
  } catch {
    return undefined
  }
}

/** DevSpace also git-pulls the helm-charts repo for every Helm step (~0.9s,
 *  three per cycle). The templates already read values files from DevSpace's
 *  local checkout (DEVSPACE_SERVICE_DEPENDENCY_PATH); use its chart too. Only
 *  for template deployments the repo does not redefine. */
function localChartPatches(template: ConfigShape | undefined, repo: ConfigShape): Patch[] {
  const chart = helmChartsDir()
  if (!existsSync(join(chart, 'service', 'Chart.yaml'))) return []
  refreshGuidelines(chart)
  return Object.entries(template?.deployments ?? {})
    .filter(([name, d]) => typeof d?.helm?.chart?.git === 'string' && !repo.deployments?.[name])
    .map(([name]) => ({
      op: 'replace',
      path: `deployments.${name}.helm.chart`,
      value: { name: '${DEVSPACE_SERVICE_DEPENDENCY_PATH}' },
    }))
}

/** The dev shell, and with it the UI's startup command, waited for the initial
 *  sync (~3.5s). The image already holds the deployed files, so Vite can start
 *  on them while the sync finishes and reloads what it changes. */
function noSyncWaitPatches(repo: ConfigShape): Patch[] {
  const sync = repo.dev?.common?.sync
  if (!Array.isArray(sync)) return []
  return sync.map((_, i) => ({
    op: 'add',
    path: `dev.common.sync[${i}].waitInitialSync`,
    value: false,
  }))
}

function helmChartsDir(): string {
  const root =
    process.env.DEVDOCK_DEVSPACE_DEPENDENCIES ?? join(homedir(), '.devspace', 'dependencies')
  return join(root, 'gitssh-git-github-com-vmockinc-helm-charts-master')
}

function cacheSeed(configText: string): string | undefined {
  try {
    const seed = (parseYaml(configText) as { vars?: Record<string, unknown> } | null)?.vars?.[
      CACHE_SEED_VAR
    ]
    return typeof seed === 'string' && seed ? seed : undefined
  } catch {
    return undefined
  }
}

/** Whether devdock runs this repo through its generated overlay. */
export function isTuned(repo: Repo): boolean {
  return overlayPlan(repo) !== undefined
}

export const CACHED_PULL_SECRET_PROFILE = 'devdock-cached-pull-secret'
/** ECR tokens last 12h; `deploy` refreshes the namespace's pull secret, and
 *  `dev`/`purge` within six hours of that reuse it instead of minting a token
 *  while loading the config (~0.6s per verb). */
const PULL_SECRET_REUSE_MS = 6 * 3600_000

function pullSecretStamp(repo: Repo): string {
  const ns = (repo.namespace || '_context').replace(/[^A-Za-z0-9_.-]/g, '_')
  const root = process.env.DEVDOCK_STATE_DIR ?? join(homedir(), '.devdock')
  return join(root, 'pull-secret', `${ns}.stamp`)
}

/** Record that a successful deploy refreshed this namespace's pull secret. */
export function markPullSecretRefreshed(repo: Repo): void {
  const stamp = pullSecretStamp(repo)
  mkdirSync(dirname(stamp), { recursive: true })
  writeFileSync(stamp, '')
}

/** Whether `dev`/`purge` may skip the pull secret for this repo now. */
export function canReusePullSecret(repo: Repo): boolean {
  if (!overlayPlan(repo)?.pullSecrets) return false
  try {
    return Date.now() - statSync(pullSecretStamp(repo)).mtimeMs < PULL_SECRET_REUSE_MS
  } catch {
    return false
  }
}

/** Whether the overlay carries a `devdock` profile to activate. */
export function hasDevdockProfile(repo: Repo): boolean {
  return (overlayPlan(repo)?.patches.length ?? 0) > 0
}

/** The config devdock points DEVSPACE_CONFIG at, or undefined for the repo's own. */
export function devdockConfigPath(repo: Repo): string | undefined {
  return repo.devspaceTemplateName || isTuned(repo) ? workloadConfigPath(repo) : undefined
}

export function workloadConfigPath(repo: Repo): string {
  const id = createHash('sha256').update(repo.name).digest('hex').slice(0, 16)
  return join(dirname(repo.configPath), `.devdock-${id}.yaml`)
}

/** DevSpace keys its local cache by config filename, independently of project
 * name. Keep a symlink beside the original so relative imports and paths retain
 * their meaning, and config edits remain visible without copying configuration. */
export function prepareWorkloadConfig(repo: Repo): void {
  const plan = overlayPlan(repo)
  if (!repo.devspaceTemplateName && !plan) return
  const alias = workloadConfigPath(repo)
  const target = basename(repo.configPath)
  if (plan) writeOverlay(alias, target, plan)
  else {
    try {
      symlinkSync(target, alias)
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error
      if (!isLink(alias) || readlinkSync(alias) !== target)
        throw new Error(`Refusing to replace workload config ${alias}`)
    }
  }

  // Local generated aliases must not appear as source changes, including in
  // worktrees. Git resolves the correct per-repository exclude path for us.
  let exclude: string
  try {
    exclude = resolve(
      repo.path,
      execFileSync('git', ['rev-parse', '--git-path', 'info/exclude'], {
        cwd: repo.path,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      }).trim(),
    )
  } catch {
    return
  }
  const rule = '.devdock-*.yaml'
  const current = existsSync(exclude) ? readFileSync(exclude, 'utf8') : ''
  if (current.split(/\r?\n/).includes(rule)) return
  mkdirSync(dirname(exclude), { recursive: true })
  appendFileSync(exclude, `\n${rule}\n`)
}

function isLink(path: string): boolean {
  try {
    return lstatSync(path).isSymbolicLink()
  } catch {
    return false
  }
}

/** A real file beside the original holding the repo's config, with the
 *  guidelines import read from a local checkout when one exists and the
 *  `devdock` profile added. Being beside the original keeps every relative path
 *  meaning the same; it is rewritten per verb, so config edits apply. Replaces
 *  only devdock's own earlier alias symlink or generated file. */
function writeOverlay(alias: string, target: string, plan: OverlayPlan): void {
  if (existsSync(alias) || isLink(alias)) {
    const ours = isLink(alias)
      ? readlinkSync(alias) === target
      : readFileSync(alias, 'utf8').startsWith(GENERATED)
    if (!ours) throw new Error(`Refusing to replace workload config ${alias}`)
  }
  const doc = parseDocument(plan.text)
  const cache = guidelinesCacheDir(plan.imp.git, plan.imp.branch)
  const local = join(cache, plan.imp.subPath)
  if (existsSync(join(local, 'devspace.yaml'))) {
    doc.setIn(['imports', plan.imp.index], doc.createNode({ path: local }))
    refreshGuidelines(cache)
  }
  if (!doc.hasIn(['functions', 'docker_login_to_ecr']))
    doc.setIn(['functions', 'docker_login_to_ecr'], ECR_LOGIN)
  const envRewrite = portableEnvRewrite(local)
  if (envRewrite && !doc.hasIn(['functions', 'prepare_local_env']))
    doc.setIn(['functions', 'prepare_local_env'], envRewrite)
  if (plan.pullSecrets) {
    const cached = doc.createNode({
      name: CACHED_PULL_SECRET_PROFILE,
      patches: [{ op: 'replace', path: 'pullSecrets', value: {} }],
    })
    if (isSeq(doc.get('profiles'))) doc.addIn(['profiles'], cached)
    else doc.set('profiles', doc.createNode([cached]))
  }
  if (plan.patches.length > 0) {
    const profile = doc.createNode({ name: DEVDOCK_PROFILE, patches: plan.patches })
    if (isSeq(doc.get('profiles'))) doc.addIn(['profiles'], profile)
    else doc.set('profiles', doc.createNode([profile]))
  }
  const tmp = alias.replace(/\.yaml$/, '.tmp.yaml') // still matches the git exclude
  writeFileSync(tmp, GENERATED + doc.toString())
  if (isLink(alias)) unlinkSync(alias)
  renameSync(tmp, alias)
}

/** The guidelines' env rewrite uses BSD `sed -i ''`, which GNU sed reads as a
 *  file name, so `sync-env` (and with it every sandbox build) fails on Linux.
 *  `-i.<suffix>` means the same on both seds; the backups are removed after. */
function portableEnvRewrite(templateDir: string): string | undefined {
  let body: unknown
  try {
    const template = parseYaml(readFileSync(join(templateDir, 'devspace.yaml'), 'utf8')) as {
      functions?: Record<string, unknown>
    } | null
    body = template?.functions?.prepare_local_env
  } catch {
    return undefined
  }
  if (typeof body !== 'string' || !body.includes("sed -i '' ")) return undefined
  return `${body.replaceAll("sed -i '' ", 'sed -i.devdock-bak ')}\nrm -f "$1.devdock-bak"`
}

const refreshing = new Map<string, number>()

/** Fast-forward the local guidelines checkout at most every ten minutes, off
 *  the verb's path; a failed pull just leaves the last good checkout. */
function refreshGuidelines(cache: string): void {
  let fetched = 0
  try {
    fetched = statSync(join(cache, '.git', 'FETCH_HEAD')).mtimeMs
  } catch {
    /* never fetched */
  }
  const last = Math.max(fetched, refreshing.get(cache) ?? 0)
  if (Date.now() - last < GUIDELINES_REFRESH_MS) return
  refreshing.set(cache, Date.now())
  const child = spawn('git', ['-C', cache, 'pull', '--ff-only', '-q'], {
    detached: true,
    stdio: 'ignore',
  })
  child.on('error', () => undefined)
  child.unref()
}
