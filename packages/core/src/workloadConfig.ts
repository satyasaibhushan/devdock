import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import {
  appendFileSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readlinkSync,
  renameSync,
  symlinkSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { parse as parseYaml, stringify } from 'yaml'
import { CACHE_SEED_VAR } from './replicas.js'
import type { Repo } from './types.js'

/** Shared guidelines templates devdock knows how to speed up, keyed by the
 *  `subPath` a repo imports from vmockinc/guidelines. */
type Template = 'ui' | 'non-ui'

/** The `devdock` profile layered over each template for devdock's own
 *  deploy/dev/purge verbs. Never applied with `-p persistent` (sandboxes): that
 *  profile removes the same kaniko block and would fail on a second removal. */
const TUNING: Partial<Record<Template, Array<Record<string, unknown>>>> = {
  // Dev images were built by kaniko with `cache: false`, so every deploy re-ran
  // apk + a full pnpm install. Build with the same in-cluster BuildKit the
  // `persistent` profile uses (one shared warm builder) and a registry cache.
  ui: [
    { op: 'remove', path: 'images.app.kaniko' },
    {
      op: 'add',
      path: 'images.app.buildKit',
      value: {
        inCluster: { nodeSelector: 'node.kubernetes.io/instance-type=t3a.xlarge' },
        args: [
          '--cache-to=mode=max,image-manifest=true,oci-mediatypes=true,type=registry,ref=${AWS_ECR_DEVSPACE_REPO}:${IMAGE_TAG}-cache',
          '--cache-from=type=registry,ref=${AWS_ECR_DEVSPACE_REPO}:${IMAGE_TAG}-cache',
        ],
      },
    },
  ],
}

export const DEVDOCK_PROFILE = 'devdock'
const GENERATED = '# Generated by devdock; overwritten on every verb.\n'

export function guidelinesTemplate(configText: string): Template | undefined {
  let doc: unknown
  try {
    doc = parseYaml(configText)
  } catch {
    return undefined
  }
  const imports = (doc as { imports?: unknown } | null)?.imports
  if (!Array.isArray(imports)) return undefined
  for (const entry of imports) {
    const { git, subPath } = (entry ?? {}) as { git?: unknown; subPath?: unknown }
    if (typeof git !== 'string' || !/[/:]vmockinc\/guidelines(\.git)?$/.test(git)) continue
    const m = typeof subPath === 'string' ? /devspace\/(ui|non-ui)\/?$/.exec(subPath) : null
    if (m) return m[1] as Template
  }
  return undefined
}

function tuningFor(repo: Repo): Array<Record<string, unknown>> | undefined {
  let text: string
  try {
    text = readFileSync(repo.configPath, 'utf8')
  } catch {
    return undefined
  }
  const template = guidelinesTemplate(text)
  const tuning = template ? TUNING[template] : undefined
  const seed = cacheSeed(text)
  if (!tuning || seed === undefined) return tuning
  return tuning.map((patch) => {
    const value = patch.value as { args?: string[] } | undefined
    if (patch.path !== 'images.app.buildKit' || !value?.args) return patch
    const from = `--cache-from=type=registry,ref=\${AWS_ECR_DEVSPACE_REPO}:${seed}-cache`
    return { ...patch, value: { ...value, args: [...value.args, from] } }
  })
}

function cacheSeed(configText: string): string | undefined {
  try {
    const seed = (parseYaml(configText) as { vars?: Record<string, unknown> } | null)?.vars?.[
      CACHE_SEED_VAR
    ]
    return typeof seed === 'string' && seed ? seed : undefined
  } catch {
    return undefined
  }
}

/** Whether devdock runs this repo through its tuned overlay (`-p devdock`). */
export function isTuned(repo: Repo): boolean {
  return tuningFor(repo) !== undefined
}

/** The config devdock points DEVSPACE_CONFIG at, or undefined for the repo's own. */
export function devdockConfigPath(repo: Repo): string | undefined {
  return repo.devspaceTemplateName || isTuned(repo) ? workloadConfigPath(repo) : undefined
}

export function workloadConfigPath(repo: Repo): string {
  const id = createHash('sha256').update(repo.name).digest('hex').slice(0, 16)
  return join(dirname(repo.configPath), `.devdock-${id}.yaml`)
}

/** DevSpace keys its local cache by config filename, independently of project
 * name. Keep a symlink beside the original so relative imports and paths retain
 * their meaning, and config edits remain visible without copying configuration. */
export function prepareWorkloadConfig(repo: Repo): void {
  const tuning = tuningFor(repo)
  if (!repo.devspaceTemplateName && !tuning) return
  const alias = workloadConfigPath(repo)
  const target = basename(repo.configPath)
  if (tuning) writeOverlay(repo, alias, target, tuning)
  else {
    try {
      symlinkSync(target, alias)
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error
      if (!isLink(alias) || readlinkSync(alias) !== target)
        throw new Error(`Refusing to replace workload config ${alias}`)
    }
  }

  // Local generated aliases must not appear as source changes, including in
  // worktrees. Git resolves the correct per-repository exclude path for us.
  let exclude: string
  try {
    exclude = resolve(
      repo.path,
      execFileSync('git', ['rev-parse', '--git-path', 'info/exclude'], {
        cwd: repo.path,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      }).trim(),
    )
  } catch {
    return
  }
  const rule = '.devdock-*.yaml'
  const current = existsSync(exclude) ? readFileSync(exclude, 'utf8') : ''
  if (current.split(/\r?\n/).includes(rule)) return
  mkdirSync(dirname(exclude), { recursive: true })
  appendFileSync(exclude, `\n${rule}\n`)
}

function isLink(path: string): boolean {
  try {
    return lstatSync(path).isSymbolicLink()
  } catch {
    return false
  }
}

/** A real file beside the original: it imports the repo's config by relative
 *  path (so its paths and edits keep their meaning) and adds the devdock profile.
 *  Replaces only devdock's own earlier alias symlink or generated file. */
function writeOverlay(
  repo: Repo,
  alias: string,
  target: string,
  tuning: Array<Record<string, unknown>>,
): void {
  if (existsSync(alias) || isLink(alias)) {
    const ours = isLink(alias)
      ? readlinkSync(alias) === target
      : readFileSync(alias, 'utf8').startsWith(GENERATED)
    if (!ours) throw new Error(`Refusing to replace workload config ${alias}`)
  }
  const body = stringify({
    version: 'v2beta1',
    name: repo.name,
    imports: [{ path: `./${target}` }],
    profiles: [{ name: DEVDOCK_PROFILE, patches: tuning }],
  })
  const tmp = alias.replace(/\.yaml$/, '.tmp.yaml') // still matches the git exclude
  writeFileSync(tmp, GENERATED + body)
  if (isLink(alias)) unlinkSync(alias)
  renameSync(tmp, alias)
}
